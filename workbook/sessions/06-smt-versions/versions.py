# 第05回と同じ架空のパッケージ5つ。この科目のために作った設定である。
# 値は「導入できるいちばん新しい版」を表す。
LATEST = {
    "app": 2,       # 版1, 版2
    "gui": 3,       # 版1, 版2, 版3
    "net": 4,       # 版1, 版2, 版3, 版4
    "db": 2,        # 版1, 版2
    "legacy": 1,    # 版1 だけ
}
